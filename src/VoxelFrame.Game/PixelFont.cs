/// <summary>
/// Пиксельный шрифт 8×8: генерируется программно из битмапов.
/// Поддерживает ASCII (32-126) и кириллицу (А-Яа-я).
/// </summary>
public static class PixelFont {
    private static Texture2D _atlas;
    private static bool _loaded;
    private const int CharW = 8, CharH = 8;
    private const int Cols = 16, ROWS = 10; // 160 слотов (16×10)
    private const int AtlasW = Cols * CharW, AtlasH = ROWS * CharH;

    // Маппинг символ → индекс в атласе (0-159)
    private static readonly Dictionary<int, int> _charMap = new();

    public static void Load() {
        if (_loaded) return;
        BuildCharMap();
        var image = Raylib.GenImageColor(AtlasW, AtlasH, new Color(0, 0, 0, 0));
        foreach (var (ch, idx) in _charMap) {
            var bmp = GetBitmap(ch);
            if (bmp == null) continue;
            int ox = (idx % Cols) * CharW;
            int oy = (idx / Cols) * CharH;
            for (int y = 0; y < CharH; y++) {
                for (int x = 0; x < CharW; x++) {
                    if ((bmp[y] & (1 << (7 - x))) != 0) {
                        Raylib.ImageDrawPixel(ref image, ox + x, oy + y, new Color(255, 255, 255, 255));
                    }
                }
            }
        }
        _atlas = Raylib.LoadTextureFromImage(image);
        Raylib.SetTextureFilter(_atlas, TextureFilter.Point);
        Raylib.UnloadImage(image);
        _loaded = true;
    }

    public static void Unload() {
        if (_loaded) { Raylib.UnloadTexture(_atlas); _loaded = false; }
    }

    public static float Measure(string text, float size) {
        float cw = size * CharW / CharH; // каждый символ = size пикселей по ширине
        return text.Length * cw;
    }

    public static void Draw(string text, float x, float y, float size, Color color) {
        float scale = size / CharH;
        float cw = CharW * scale;
        for (int i = 0; i < text.Length; i++) {
            int ch = text[i];
            if (!_charMap.TryGetValue(ch, out int idx)) continue;
            int col = idx % Cols, row = idx / Cols;
            var src = new Rectangle(col * CharW, row * CharH, CharW, CharH);
            var dst = new Rectangle(x + i * cw, y, cw, size);
            Raylib.DrawTexturePro(_atlas, src, dst, Vector2.Zero, 0f, color);
        }
    }

    public static void DrawShadowed(string text, float x, float y, float size, Color color) {
        Draw(text, x + 1f, y + 1f, size, new Color(0, 0, 0, 180));
        Draw(text, x, y, size, color);
    }

    public static void DrawCentered(string text, float cx, float y, float size, Color color) =>
        Draw(text, cx - Measure(text, size) / 2f, y, size, color);

    private static void BuildCharMap() {
        int idx = 0;
        // ASCII 32-126
        for (int c = 32; c <= 126; c++) _charMap[c] = idx++;
        // Кириллица А-Я (-uppercase)
        for (int c = 0x410; c <= 0x42F; c++) _charMap[c] = idx++;
        // Кириллица а-я (lowercase)
        for (int c = 0x430; c <= 0x44F; c++) _charMap[c] = idx++;
        _charMap[0x401] = idx++; // Ё
        _charMap[0x451] = idx++; // ё
    }

